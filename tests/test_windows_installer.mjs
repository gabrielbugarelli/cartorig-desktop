import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read = path => readFileSync(new URL('../'+path, import.meta.url),'utf8');
const iss=read('installer/cartorig-desktop.iss');
const script=read('scripts/build-windows-installer.ps1');
const smoke=read('scripts/test-windows-installer.ps1');
assert.match(iss,/AppName=\{#AppName\}/);
assert.match(iss,/AppVersion=\{#AppVersion\}/);
assert.match(iss,/AppId=\{\{3928EE55-FFF5-5966-A76E-186D41369FFF\}/,'Stable AppId for future installer updates');
assert.match(iss,/PrivilegesRequired=lowest/,'Install in user profile without administrator rights');
assert.match(iss,/DefaultDirName=\{localappdata\}\\Programs\\CartoRig Desktop/);
assert.match(iss,/ArchitecturesAllowed=x64compatible/);
assert.match(iss,/CloseApplications=yes/);
assert.match(iss,/RestartApplications=no/);
assert.match(iss,/UninstallDisplayName=CartoRig Desktop/);
assert.match(iss,/Name: "\{autoprograms\}\\CartoRig Desktop"/);
assert.match(iss,/Name: "\{autodesktop\}\\CartoRig Desktop"/);
assert.match(iss,/Source: "\.\.\\dist\\\{#SourceExe\}"; DestDir: "\{app\}"; DestName: "\{#AppExeName\}"/);
assert.match(iss,/Filename: "\{app\}\\\{#AppExeName\}"; Description: "Iniciar CartoRig Desktop"/);
assert.doesNotMatch(iss,/\[(?:Registry|UninstallDelete)\]/i,'Never remove profile settings or create global registry changes');
assert.doesNotMatch(iss,/PrivilegesRequired=admin/);
assert.match(iss,/Source: "\.\.\\LICENSE"/);
assert.match(script,/ExpectedSHA256/,'Reject artifacts without an approved SHA256');
assert.match(script,/Get-FileHash/);
assert.match(script,/ISCC\.exe/);
assert.match(script,/Get-AuthenticodeSignature/,'Do not imply SmartScreen has been resolved');
assert.match(smoke,/--self-check/,'Verify the installed executable, not only extraction');
assert.match(smoke,/unins000\.exe/,'Verify full uninstallation');
assert.match(smoke,/Get-FileHash/,'Installed file must match the approved source');
assert.match(smoke,/installer-qa-keep-data/,'User app data must survive uninstallation');
console.log('WINDOWS INSTALLER POLICY PASS: per-user, stable AppId, validated EXE, shortcuts, uninstaller and preserved data');
