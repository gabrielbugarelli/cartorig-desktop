import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {newDocument,validateDocument,SceneStore,MAP_LABEL_KINDS,MAP_LABEL_SIZES} from '../assets/scene-core.js';
import {layoutMapLabels,labelOptions} from '../assets/map-labels.js';
const pack=JSON.parse(readFileSync(new URL('../assets/geodata/map_labels.json',import.meta.url)));
assert.equal(pack.countries.length,177);
assert.ok(pack.states.length>=4500);
assert.ok(pack.national_capitals.length>=190);
assert.ok(pack.cities.length>=4000);
for(const kind of MAP_LABEL_KINDS)assert.ok(pack[kind]?.length,kind);
const store=new SceneStore();const doc=store.doc;
assert.ok(doc.map_labels.enabled.countries);
assert.ok(doc.map_labels.enabled.national_capitals);
validateDocument(doc);
const initial=doc.map_labels.enabled.states;
assert.equal(initial,false);
assert.ok(store.execute({type:'SetMapLabelOption',section:'enabled',key:'states',value:true}));
assert.equal(store.doc.map_labels.enabled.states,true);
store.undo();assert.equal(store.doc.map_labels.enabled.states,false);
store.redo();assert.equal(store.doc.map_labels.enabled.states,true);
assert.ok(store.execute({type:'SetMapLabelOption',section:'sizes',key:'states',value:19}));
assert.equal(store.doc.map_labels.sizes.states,19);
assert.ok(store.execute({type:'SetMapLabelOption',section:'colors',key:'states',value:'#dedede'}));
assert.equal(store.doc.map_labels.colors.states,'#dedede');
assert.ok(store.execute({type:'SetMapLabelOption',section:'colors',key:'states',value:null}));
assert.equal(store.doc.map_labels.colors.states,undefined);
assert.throws(()=>store.execute({type:'SetMapLabelOption',section:'enabled',key:'states',value:'yes'}));
assert.throws(()=>store.execute({type:'SetMapLabelOption',section:'sizes',key:'states',value:1000}));
assert.throws(()=>store.execute({type:'SetMapLabelOption',section:'colors',key:'countries',value:'red'}));
assert.throws(()=>store.execute({type:'SetMapLabelOption',section:'enabled',key:'evil',value:true}));
const legacy=structuredClone(store.doc);delete legacy.map_labels;validateDocument(legacy);
assert.deepEqual(labelOptions(legacy).enabled,{});
const copy=structuredClone(store.doc);copy.camera.zoom=4;copy.camera.center_lon=18;copy.camera.center_lat=51;
const ctx={font:'',measureText:name=>({width:name.length*8})};
const project=(_doc,lon,lat,w,h)=>[w/2+(lon-18)*30,h/2-(lat-51)*30];
const style={text:'#ddeeff',ocean:'#123456'};
const places=layoutMapLabels(ctx,copy,pack,1200,750,project,style);
assert.ok(places.length>4,'Regional Europe should show country and capital names');
assert.ok(places.some(x=>x.kind==='countries'));
assert.ok(places.some(x=>x.kind==='national_capitals'));
for(const item of places)assert.ok(item.x>=0&&item.x<1200&&item.y>=0&&item.y<750);
const old=places.length;
for(const kind of MAP_LABEL_KINDS)copy.map_labels.enabled[kind]=false;
assert.equal(layoutMapLabels(ctx,copy,pack,1200,750,project,style).length,0);
assert.ok(old>0);
console.log('PASS 2.0.3: offline names, toggle/undo/redo, project validation and placements');
