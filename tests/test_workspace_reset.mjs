import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {SceneStore,newDocument,madeObject} from '../assets/scene-core.js';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const store=new SceneStore(newDocument());
assert.throws(()=>store.execute({type:'ResetScene'}),/confirmation/i);
store.execute({type:'SetProjectName',name:'Historical Draft'});
const projectId=store.doc.project_id,created=store.doc.created_at;
const france=madeObject('Region','France',{region_kind:'Country',source:{dataset_id:'ne_admin0_110m',feature_id:'FRA'}});
store.execute({type:'CreateObject',object:france});
store.execute({type:'SetCameraPose',pose:{zoom:5,center_lon:11}});
store.execute({type:'SetTextureVisibility',enabled:false});
store.setSelection([france.id]);
const before=JSON.stringify(store.doc);
assert.equal(store.execute({type:'ResetScene',confirm:true}),true);
const baseline=newDocument();
assert.equal(store.doc.project_id,projectId);
assert.equal(store.doc.name,'Historical Draft');
assert.equal(store.doc.created_at,created);
assert.equal(store.doc.camera.zoom,baseline.camera.zoom);
assert.equal(store.doc.render_options.textures_enabled,true);
assert.deepEqual(store.doc.map_labels,baseline.map_labels);
assert.deepEqual(Object.values(store.doc.objects).map(o=>o.type).sort(),['Borders','Grid','WorldMap']);
assert.equal(store.selection.length,0);
assert.equal(store.dirty,true);
assert.equal(store.undo(),true);
assert.equal(JSON.stringify(store.doc),before);
assert.deepEqual(store.selection,[france.id]);
assert.equal(store.redo(),true);
assert.equal(store.doc.scene.root_ids.length,3);
const index=read('assets/index.html'),studio=read('assets/style-studio.js'),navigation=read('assets/navigation-ui.js'),layout=read('assets/ux-layout.css'),app=read('assets/app.js');
assert.match(index,/<button id="saveProject"[^>]*>Save<\/button><button id="resetMap"[^>]*>Reset<\/button>/);
assert.equal((index.match(/id="toggleScene"/g)||[]).length,1);
assert.equal((index.match(/id="toggleInspector"/g)||[]).length,1);
assert.ok(index.indexOf('id="toggleScene"')<index.indexOf('id="projectName"'));
assert.ok(index.indexOf('id="toggleScene"')>index.indexOf('class="stage-heading"'));
assert.ok(index.indexOf('id="toggleInspector"')>index.indexOf('id="worldView"'));
assert.ok(index.includes('aria-controls="leftSidebar"')&&index.includes('aria-controls="rightSidebar"'));
assert.ok(index.includes('>◨</button>')&&index.includes('>◧</button>'));
assert.doesNotMatch(studio,/Reset options|Reset all object overrides|ux-reset-options/);
assert.match(navigation,/aria-expanded/);
assert.match(layout,/@media\(max-width:760px\)[\s\S]*\.stage-heading/);
assert.match(app,/\$\('resetMap'\)\.onclick=resetMap/);
console.log('WORKSPACE RESET PASS: reset / project identity / undo / redo / layout');
