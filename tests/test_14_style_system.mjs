/* M4 Style Studio/Region Editor contract tests — Node 22+. */
import assert from 'node:assert/strict';
import {SceneStore,newDocument,madeObject,COLORS} from '../assets/scene-core.js';
import {paletteFor,resolveStyle,parseStylePreset,styleToFile,isColor} from '../assets/style-resolver.js';
const st=new SceneStore(),doc=st.doc;
for(let key of ['dark','atlas','tactical','relief','satellite','night','elevation','historical','terrain'])assert.ok(COLORS[key],key);
let brazil=madeObject('Region','Brazil',{source:{dataset_id:'natural-earth',feature_id:'BRA'},region_kind:'Country',style:{}});
let italy=madeObject('Region','Italy',{source:{dataset_id:'natural-earth',feature_id:'ITA'},region_kind:'Country',style:{}});
assert.ok(st.execute({type:'CreateObject',object:brazil}));assert.ok(st.execute({type:'CreateObject',object:italy}));
assert.equal(resolveStyle(st.doc,brazil).fill_color,COLORS.dark.accent);
st.execute({type:'SetObjectStyle',id:brazil.id,values:{fill_color:'#ff0000',stroke_width:4,shadow_enabled:true,shadow_blur:10,glow_enabled:true,glow_radius:12}});
assert.equal(resolveStyle(st.doc,st.doc.objects[brazil.id]).fill_color,'#ff0000');
st.execute({type:'ApplyTheme',id:'atlas'});
assert.equal(resolveStyle(st.doc,st.doc.objects[brazil.id]).fill_color,'#ff0000');
assert.equal(resolveStyle(st.doc,st.doc.objects[italy.id]).fill_color,COLORS.atlas.accent);
assert.equal(paletteFor(st.doc).ocean,COLORS.atlas.ocean);
let before=structuredClone(st.doc.objects[brazil.id].style);
st.execute({type:'ResetStyleProperty',id:brazil.id,key:'fill_color'});
assert.equal(resolveStyle(st.doc,st.doc.objects[brazil.id]).fill_color,COLORS.atlas.accent);
assert.equal(st.doc.objects[brazil.id].style.stroke_width,4);assert.equal(st.doc.objects[brazil.id].style.shadow_enabled,true);
st.undo();assert.deepEqual(st.doc.objects[brazil.id].style,before);
st.redo();assert.ok(!('fill_color' in st.doc.objects[brazil.id].style));
st.execute({type:'SetThemeProperty',key:'terrain_enabled',value:true});st.execute({type:'SetThemeProperty',key:'terrain_strength',value:1});
st.execute({type:'SetThemeProperty',key:'atmosphere_vignette',value:.65});
st.execute({type:'SetCategoryStyle',object_type:'Region',key:'stroke_width',value:6});
assert.equal(resolveStyle(st.doc,st.doc.objects[italy.id]).stroke_width,6);
assert.equal(resolveStyle(st.doc,st.doc.objects[brazil.id]).stroke_width,4);
assert.throws(()=>st.execute({type:'SetThemeProperty',key:'terrain_strength',value:Infinity}),/Invalid/);
assert.throws(()=>st.execute({type:'SetObjectStyle',id:brazil.id,values:{shadow_blur:101}}),/Invalid/);
assert.throws(()=>st.execute({type:'SetObjectStyle',id:brazil.id,values:{blend_mode:'difference'}}),/Unsupported/);
assert.equal(st.doc.theme.overrides.terrain_strength,1);
let g=madeObject('Group','Group',{children:[]});st.execute({type:'CreateObject',object:g});st.execute({type:'MoveObject',id:italy.id,parent_id:g.id});
st.execute({type:'SetGroupChildStyle',id:g.id,key:'fill_color',value:'#00ff00'});
assert.equal(resolveStyle(st.doc,st.doc.objects[italy.id]).fill_color,'#00ff00');
assert.equal(resolveStyle(st.doc,st.doc.objects[brazil.id]).fill_color,COLORS.atlas.accent);
st.execute({type:'SetObjectStyle',id:italy.id,values:{fill_color:'#332211'}});
assert.equal(resolveStyle(st.doc,st.doc.objects[italy.id]).fill_color,'#332211');
st.execute({type:'SaveUserStyle',name:'Atlas Modified'});
let preset=st.doc.style_library.at(-1);
assert.equal(preset.overrides.terrain_strength,1);
assert.equal(preset.defaults.Region.stroke_width,6);
let file=styleToFile(preset);assert.equal(parseStylePreset(file).name,'Atlas Modified');
assert.throws(()=>st.execute({type:'ImportUserStyle',content:file}),/already exists/);
assert.ok(st.execute({type:'ImportUserStyle',content:file,on_conflict:'duplicate'}));
assert.notEqual(st.doc.style_library.at(-1).id,preset.id);
st.execute({type:'ApplyTheme',id:preset.id});
assert.equal(st.doc.theme.overrides.terrain_strength,1);
assert.ok(st.undo());assert.ok(st.redo());
assert.throws(()=>parseStylePreset(JSON.stringify({format:'cartorig-style',schema_version:'1.0.0',name:'bad',palette:{texture:'https://evil'},defaults:{}})),/Invalid/);
assert.throws(()=>parseStylePreset(JSON.stringify({format:'cartorig-style',schema_version:'1.0.0',name:'bad',palette:{land:'#ffffff'},defaults:{Region:{glow_radius:100000}}})),/Invalid/);
assert.throws(()=>parseStylePreset('<script>alert(1)</script>'),/Invalid/);
assert.ok(isColor('#fff')&&isColor('#ff000080'));
// Legacy 1.3 projects have neither type_defaults nor style_library and remain readable.
const legacy=newDocument();delete legacy.style_library;delete legacy.theme.type_defaults;legacy.theme.id='dark';let restored=new SceneStore(legacy);assert.equal(resolveStyle(restored.doc,{...brazil,style:{fill_color:'#ff0000'}}).fill_color,'#ff0000');
const original=st.doc.objects[brazil.id].source.feature_id;
const replacement={region_kind:'State',source:{dataset_id:'ne_admin1',feature_id:'CA-ON',source_version:'10m'},geometry:{type:'Polygon',coordinates:[[[0,0],[10,0],[10,10],[0,10],[0,0]]]},geo_source_info:{name:'Ontario',scale:'10m'}};
assert.ok(st.execute({type:'ReplaceRegionGeography',id:brazil.id,geo:replacement}));
assert.equal(st.doc.objects[brazil.id].source.feature_id,'CA-ON');assert.equal(st.doc.objects[brazil.id].style.shadow_enabled,true);
assert.ok(st.undo());assert.equal(st.doc.objects[brazil.id].source.feature_id,original);
assert.throws(()=>st.execute({type:'ReplaceRegionGeography',id:brazil.id,geo:{...replacement,geometry:null}}),/Polygon source unavailable/);
assert.equal(st.doc.objects[brazil.id].source.feature_id,original);
console.log('M4 style inheritance, independent overrides, groups, effects contracts, import/export, undo and legacy compatibility: PASS');
