import assert from 'node:assert/strict';
import {SceneStore,newDocument,COLORS,madeObject} from '../assets/scene-core.js';
import {BUILTIN_LOOK_DEFAULTS,themeValue,resolveStyle,paletteFor} from '../assets/style-resolver.js';
const st=new SceneStore(newDocument());
const obj=madeObject('Region','Brazil',{region_kind:'Country',source:{dataset_id:'natural-earth',feature_id:'BRA'},style:{fill_color:'#d71f20'}});
st.execute({type:'CreateObject',object:obj});
st.execute({type:'ApplyTheme',id:'relief'});
const relief=Object.fromEntries(['texture_source','ocean_mode','terrain_contrast','terrain_saturation','terrain_enabled','terrain_strength','atmosphere_vignette','atmosphere_tint_mix'].map(k=>[k,themeValue(st.doc,k)]));
assert.equal(relief.texture_source,'shadedrelief');assert.equal(relief.atmosphere_vignette,0);
st.execute({type:'ApplyTheme',id:'terrain'});
const cinematic=Object.fromEntries(Object.keys(relief).map(k=>[k,themeValue(st.doc,k)]));
assert.equal(cinematic.texture_source,'etopo1');assert.equal(cinematic.ocean_mode,'solid');assert.equal(cinematic.terrain_enabled,true);
assert.ok(cinematic.terrain_contrast>relief.terrain_contrast);
assert.ok(cinematic.terrain_saturation<relief.terrain_saturation);
assert.ok(cinematic.atmosphere_vignette>relief.atmosphere_vignette);
assert.ok(cinematic.atmosphere_tint_mix>relief.atmosphere_tint_mix);
assert.notDeepEqual(paletteFor({...st.doc,theme:{...st.doc.theme,id:'relief'}}),paletteFor(st.doc));
assert.notEqual(COLORS.terrain.texture,COLORS.relief.texture);
assert.equal(resolveStyle(st.doc,st.doc.objects[obj.id]).fill_color,'#d71f20');
st.execute({type:'SetThemeProperty',key:'terrain_contrast',value:1.8});
assert.equal(themeValue(st.doc,'terrain_contrast'),1.8);
st.execute({type:'SetThemeProperty',key:'terrain_contrast',value:null});
assert.equal(themeValue(st.doc,'terrain_contrast'),BUILTIN_LOOK_DEFAULTS.terrain.terrain_contrast);
st.execute({type:'ApplyTheme',id:'relief'});
assert.equal(themeValue(st.doc,'terrain_contrast'),1);
assert.equal(resolveStyle(st.doc,st.doc.objects[obj.id]).fill_color,'#d71f20');
console.log('1.4.3 scene looks independent texture, atmosphere and style inheritance: PASS',relief,cinematic);
