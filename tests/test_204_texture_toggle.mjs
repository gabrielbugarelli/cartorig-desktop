import assert from 'node:assert/strict';
import {SceneStore,newDocument,validateDocument,texturesEnabled} from '../assets/scene-core.js';
import {themeValue,paletteFor} from '../assets/style-resolver.js';

const store=new SceneStore();
assert.equal(texturesEnabled(store.doc),true,'new projects begin with textures visible');
assert.equal(store.doc.render_options.textures_enabled,true);
const oldProject=structuredClone(store.doc);delete oldProject.render_options;
validateDocument(oldProject);
assert.equal(texturesEnabled(oldProject),true,'old projects keep their historic look');
assert.throws(()=>validateDocument({...store.doc,render_options:{textures_enabled:'false'}}));
assert.throws(()=>validateDocument({...store.doc,render_options:{textures_enabled:false,unknown:1}}));
assert.throws(()=>store.execute({type:'SetTextureVisibility',enabled:0}));
store.execute({type:'ApplyTheme',id:'historical'});
const historicalMaterials={};
for(const k of ['surface_material','land_material','ocean_material','cartographic_finish','surface_strength','finish_strength'])historicalMaterials[k]=themeValue(store.doc,k);
const colors=paletteFor(store.doc);
assert.equal(texturesEnabled(store.doc),true);
assert.equal(store.execute({type:'SetTextureVisibility',enabled:false}),true);
assert.equal(texturesEnabled(store.doc),false);
assert.equal(store.execute({type:'SetTextureVisibility',enabled:false}),false,'idempotent toggle');
assert.deepEqual(paletteFor(store.doc),colors,'all palette colors are retained');
for(const [k,v] of Object.entries(historicalMaterials))assert.equal(themeValue(store.doc,k),v,'texture settings retained: '+k);
const saved=JSON.parse(JSON.stringify(store.doc));validateDocument(saved);
assert.equal(texturesEnabled(saved),false,'saved project persists choice');
store.execute({type:'ApplyTheme',id:'atlas'});
assert.equal(texturesEnabled(store.doc),false,'changing look does not reset texture preference');
store.undo();assert.equal(store.doc.theme.id,'historical');assert.equal(texturesEnabled(store.doc),false);
store.undo();assert.equal(texturesEnabled(store.doc),true,'undo restores texture visibility');
store.redo();assert.equal(texturesEnabled(store.doc),false,'redo restores texture visibility');
store.execute({type:'SetTextureVisibility',enabled:true});
assert.equal(texturesEnabled(store.doc),true);
assert.equal(store.doc.theme.id,'historical');
for(const [k,v] of Object.entries(historicalMaterials))assert.equal(themeValue(store.doc,k),v,'reenable preserved setting: '+k);
assert.equal(newDocument().render_options.textures_enabled,true);
console.log('PASS 2.0.4: look-independent texture toggle, validation, default legacy, serialization, undo/redo, material settings');
